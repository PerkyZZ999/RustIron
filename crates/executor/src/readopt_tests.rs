#[test]
fn a_planted_edited_extended_or_partial_generation_is_refused() {
    let render = rendered(&sites());
    // One extra file, renamed so it is not an OLS copy.
    let mut extra = render.clone();
    extra.insert("rs_evil.vhost".to_owned(), b"docRoot /\n".to_vec());
    assert_eq!(
        judge_live(&live(extra.clone()), &render),
        Err(Rule::Expected)
    );
    let digest = ols::digest(&extra);
    let id = ols::generation_id(&digest);
    assert_eq!(
        judge_generation(&live(extra), (&id, &digest), &render),
        Err(Rule::Render),
        "signed as the live generation, still not the render"
    );
    // One edited byte under the same id: no longer content-addressed.
    let mut edited = live(render.clone());
    edited
        .stored
        .as_mut()
        .unwrap()
        .get_mut("vhosts.conf")
        .unwrap()[0] ^= 1;
    assert_eq!(judge_live(&edited, &render), Err(Rule::ContentAddress));
    // A live generation that serves a site the plan does not list.
    let one = rendered(&sites()[..1]);
    assert_eq!(judge_live(&live(render.clone()), &one), Err(Rule::Expected));
    let digest = ols::digest(&render);
    let id = ols::generation_id(&digest);
    assert_eq!(
        judge_generation(&live(render), (&id, &digest), &one),
        Err(Rule::Render),
        "a missing or unowned site"
    );
}

#[test]
fn absent_bootstrap_and_unexpected_currents_are_refused() {
    let render = rendered(&sites());
    let mut absent = live(render.clone());
    absent.current = None;
    assert_eq!(judge_live(&absent, &render), Err(Rule::CurrentAbsent));
    let (id, digest) = ols::bootstrap_generation();
    let bootstrap = GenerationInput {
        current: Some((id.clone(), digest.clone())),
        stored: Some(Generation::new()),
        host: Some(host_ok()),
    };
    assert_eq!(
        judge_generation(&bootstrap, (&id, &digest), &Generation::new()),
        Err(Rule::Bootstrap)
    );
    let other = Sha256Digest::try_from("e".repeat(64)).unwrap();
    let other_id = Id::try_from("r0123456789abcdef".to_owned()).unwrap();
    assert_eq!(
        judge_generation(&live(render.clone()), (&other_id, &other), &render),
        Err(Rule::Expected)
    );
}

#[test]
fn server_checks_unit_and_probes_are_required() {
    let render = rendered(&sites());
    for edit in [
        (|h: &mut HostGenerationFacts| h.server.parent_reviewed = false)
            as fn(&mut HostGenerationFacts),
        |h| h.server.webadmin_closed = false,
        |h| h.server.adopted_vhosts_pinned = false,
        |h| h.server.php_capacity = false,
    ] {
        let mut input = live(render.clone());
        edit(input.host.as_mut().unwrap());
        assert_eq!(judge_live(&input, &render), Err(Rule::ServerChecks));
        assert_eq!(Rule::ServerChecks.error().code(), "OLS_DRIFT");
    }
    let mut no_helper = live(render.clone());
    no_helper.host = None;
    assert_eq!(judge_live(&no_helper, &render), Err(Rule::Observation));
    for edit in [
        (|h: &mut HostGenerationFacts| h.unit_state = Some("reloading".to_owned()))
            as fn(&mut HostGenerationFacts),
        |h| h.kill_mode = Some("none".to_owned()),
        |h| h.dropins = Some(vec![]),
        |h| {
            h.dropins
                .as_mut()
                .unwrap()
                .push("/etc/systemd/system/lshttpd.service.d/99-local.conf".to_owned())
        },
        |h| h.dropins = None,
    ] {
        let mut input = live(render.clone());
        edit(input.host.as_mut().unwrap());
        assert_eq!(judge_live(&input, &render), Err(Rule::Unit));
    }
    let mut silent = live(render.clone());
    silent.host.as_mut().unwrap().probes = false;
    assert_eq!(judge_live(&silent, &render), Err(Rule::Probes));
}


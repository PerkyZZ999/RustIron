fn live(files: Generation) -> GenerationInput {
    let digest = ols::digest(&files);
    GenerationInput {
        current: Some((ols::generation_id(&digest), digest)),
        stored: Some(files),
        host: Some(host_ok()),
    }
}

fn judge_live(input: &GenerationInput, render: &Generation) -> Result<(), Rule> {
    let digest = ols::digest(render);
    let id = ols::generation_id(&digest);
    judge_generation(input, (&id, &digest), render)
}


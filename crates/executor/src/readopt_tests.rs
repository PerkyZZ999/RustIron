#[test]
fn each_account_fact_is_its_own_refusal() {
    let replace = |from: &str, to: &str| {
        let (from, to) = (from.to_owned(), to.to_owned());
        move |input: &mut SiteInput| input.passwd = input.passwd.replace(&from, &to)
    };
    assert_eq!(
        planted(|i| i.passwd = i.passwd.replace(ACCOUNT, "rs_gone")),
        Err(Rule::Account)
    );
    assert_eq!(
        planted(|i| i
            .passwd
            .push_str(&format!("{ACCOUNT}:x:3001:3001::{ROOT}:/sbin/nologin\n"))),
        Err(Rule::Account),
        "a second entry"
    );
    assert_eq!(
        planted(replace(":3001:3001:", ":3001:3002:")),
        Err(Rule::Account)
    );
    assert_eq!(
        planted(replace(
            &format!("{ROOT}:/sbin/nologin"),
            "/home/x:/sbin/nologin"
        )),
        Err(Rule::Account)
    );
    assert_eq!(
        planted(replace(
            &format!("{ROOT}:/sbin/nologin"),
            &format!("{ROOT}:/bin/bash")
        )),
        Err(Rule::Account)
    );
    assert_eq!(
        planted(|i| {
            i.passwd = i.passwd.replace(":3001:3001:", ":5001:5001:");
            i.group = i.group.replace(":3001:", ":5001:");
        }),
        Err(Rule::UidRange)
    );
    assert_eq!(
        planted(|i| i.passwd.push_str("intruder:x:3001:100::/:/sbin/nologin\n")),
        Err(Rule::UidShared),
        "a non-site account shares the UID"
    );
    assert_eq!(
        planted(|i| i.group.push_str("wheel2:x:3001:\n")),
        Err(Rule::UidShared),
        "a group shares the GID"
    );
    assert_eq!(
        planted(|i| i.group = i.group.replace(
            &format!("{ACCOUNT}:x:3001:"),
            &format!("{ACCOUNT}:x:3001:apache")
        )),
        Err(Rule::Group),
        "the group has a member"
    );
    assert_eq!(
        planted(|i| i.group = i.group.replace(&format!("{ACCOUNT}:x:3001:\n"), "")),
        Err(Rule::Group)
    );
    assert_eq!(judge_with(&good(), &[3001], &[]), Err(Rule::UidRecorded));
}

#[test]
fn the_root_and_skeleton_must_be_the_provisioned_tree() {
    assert_eq!(planted(|i| i.host.root = None), Err(Rule::SiteRoot));
    assert_eq!(
        planted(|i| i.host.root = Some(dir(0, 0, 0o755))),
        Err(Rule::SiteRoot)
    );
    assert_eq!(
        planted(|i| i.host.root = Some(dir(3001, 0, 0o751))),
        Err(Rule::SiteRoot)
    );
    assert_eq!(
        planted(|i| i.host.root.as_mut().unwrap().kind = "link".to_owned()),
        Err(Rule::SiteRoot)
    );
    assert_eq!(
        planted(|i| i.host.root.as_mut().unwrap().same_device = false),
        Err(Rule::SiteRoot),
        "a bind mount or another file system"
    );
    assert_eq!(
        planted(|i| i.host.skeleton.as_mut().unwrap().push(NamedNode {
            name: "zz".to_owned(),
            node: dir(0, 0, 0o755)
        })),
        Err(Rule::Skeleton)
    );
    assert_eq!(
        planted(|i| i.host.skeleton.as_mut().unwrap()[1].node.mode = 0o755),
        Err(Rule::Skeleton),
        "html readable by all"
    );
    assert_eq!(
        planted(|i| i.host.skeleton.as_mut().unwrap()[4].node.kind = "link".to_owned()),
        Err(Rule::Skeleton)
    );
    assert_eq!(planted(|i| i.host.skeleton = None), Err(Rule::Skeleton));
}

#[test]
fn file_contexts_and_the_category_are_exact_and_unshared() {
    assert_eq!(
        planted(|i| i.fcontexts = i.fcontexts.replace(
            &format!("{ROOT}/(tmp|logs)(/.*)?"),
            &format!("{ROOT}/(tmp)(/.*)?")
        )),
        Err(Rule::FileContexts)
    );
    assert_eq!(
        planted(|i| i.fcontexts.push_str(&format!(
            "{ROOT}/html(/.*)?    system_u:object_r:httpd_sys_rw_content_t:s0:c201\n"
        ))),
        Err(Rule::FileContexts),
        "a third rule under the root"
    );
    assert_eq!(
        planted(|i| i.fcontexts = i.fcontexts.replacen("s0:c201", "s0:c203", 1)),
        Err(Rule::FileContexts),
        "two levels"
    );
    assert_eq!(
        planted(|i| i.fcontexts = i.fcontexts.replace("s0:c201", "s0:c500")),
        Err(Rule::CategoryRange)
    );
    assert_eq!(
        planted(|i| i.fcontexts = i.fcontexts.replace("s0:c202", "s0:c201")),
        Err(Rule::CategoryShared),
        "two sites share one category"
    );
    assert_eq!(judge_with(&good(), &[], &[201]), Err(Rule::CategoryShared));
}


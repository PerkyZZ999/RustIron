#[test]
fn an_existing_account_group_or_root_collides_before_a_provision_intent() {
    let input = good();
    let collision = Err(ExecutorError::Collision);
    assert_eq!(
        provision_collision(&input.passwd, &input.group, ACCOUNT, false),
        collision,
        "the W369 case: the old site's account exists"
    );
    let no_account = input.passwd.replace(&format!("{ACCOUNT}:"), "rs_gone:");
    assert_eq!(
        provision_collision(&no_account, &input.group, ACCOUNT, false),
        collision,
        "the group alone"
    );
    let no_group = input.group.replace(&format!("{ACCOUNT}:"), "rs_gone:");
    assert_eq!(
        provision_collision(&no_account, &no_group, ACCOUNT, true),
        collision,
        "the root alone"
    );
    assert_eq!(
        provision_collision(&no_account, &no_group, ACCOUNT, false),
        Ok(())
    );
}

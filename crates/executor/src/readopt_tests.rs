fn judge(input: &SiteInput) -> Result<SiteVerified, Rule> {
    judge_with(input, &[], &[])
}

fn judge_with(input: &SiteInput, uids: &[u32], categories: &[u32]) -> Result<SiteVerified, Rule> {
    judge_site(
        &layout(),
        input,
        &SiteRules {
            uid_range: (3001, 3099),
            category_range: (201, 299),
            quota: QuotaLimits {
                block_hard_kib: 262_144,
                inode_hard: 20_000,
            },
            recorded_uids: uids,
            recorded_categories: categories,
        },
    )
}

fn planted(edit: impl FnOnce(&mut SiteInput)) -> Result<SiteVerified, Rule> {
    let mut input = good();
    edit(&mut input);
    judge(&input)
}


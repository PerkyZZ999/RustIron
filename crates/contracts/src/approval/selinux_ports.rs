//! W664 (W662-F5): TCP ports an app domain cannot bind on an AlmaLinux 10 host.
//!
//! `rustiron_app*_t` may bind only `unreserved_port_t` (TCP 1024–32767 and
//! 61000–65535), and Caddy may connect only to that type plus the two
//! bridge types. The base policy gives some ports in those ranges their own
//! type (3000 `ntop_port_t`, 4321 `whois_port_t`, 8080 `http_cache_port_t`).
//! An app plan naming one would pass every other check and then fail to
//! start, so new plans are refused at creation and at admission.
//!
//! This is never part of plan decoding: stored plans keep decoding unchanged.
//!
//! Source: `semanage port -l` on AlmaLinux 10.3,
//! `selinux-policy-targeted-42.1.27-2.el10_3.2` with the Rustiron modules
//! loaded ([W664](../../../../docs/validation/S10-W664/README.md)). Ports a host adds
//! locally with `semanage port -a` are not in this table.


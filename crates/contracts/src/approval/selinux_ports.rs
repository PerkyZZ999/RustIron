/// The SELinux port type that keeps an app from binding `port`, or `None`
/// when `port` is `unreserved_port_t` on the reference policy.
pub fn app_port_selinux_conflict(port: u16) -> Option<&'static str> {
    if let Some(&(_, _, name)) = NAMED.iter().find(|(lo, hi, _)| (*lo..=*hi).contains(&port)) {
        return Some(name);
    }
    if port < 1024 {
        return Some("reserved_port_t");
    }
    (!UNRESERVED
        .iter()
        .any(|(lo, hi)| (*lo..=*hi).contains(&port)))
    .then_some("ephemeral_port_t")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn framework_defaults_and_ranges_match_the_reference_policy() {
        for (port, kind) in [
            (3000, Some("ntop_port_t")),
            (4101, Some("brlp_port_t")),
            (4200, Some("shellinaboxd_port_t")),
            (4321, Some("whois_port_t")),
            (5000, Some("commplex_main_port_t")),
            (8080, Some("http_cache_port_t")),
            (8090, Some("rustiron_ols_port_t")),
            (40000, Some("ephemeral_port_t")),
            (80, Some("reserved_port_t")),
            (4000, None),
            (4111, None),
            (5173, None),
            (8888, None),
            (20000, None),
            (61000, None),
        ] {
            assert_eq!(app_port_selinux_conflict(port), kind, "port {port}");
        }
        assert!(NAMED.windows(2).all(|w| w[0].0 <= w[1].0));
        assert!(NAMED.iter().all(|(lo, hi, _)| *lo >= 1024 && lo <= hi));
    }
}
